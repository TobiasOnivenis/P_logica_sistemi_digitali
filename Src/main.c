/**
  * @brief  Connects the SHT40AD1B driver (X-CUBE-MEMS1) to I2C2 and initializes it.
  * @retval SHT40AD1B_OK if the sensor answers, SHT40AD1B_ERROR otherwise
  */
static int32_t SHT40_Setup(void)
{
  SHT40AD1B_IO_t io = {0};

  io.Init    = SHT40_IO_Init;
  io.DeInit  = SHT40_IO_DeInit;
  io.BusType = SHT40AD1B_I2C_BUS;
  /* 0x89 = (0x44 << 1) | 1. In 7-bit mode the I2C peripheral only uses
     address bits 7..1; the read/write bit is added by the HAL. */
  io.Address = SHT40AD1B_I2C_ADDRESS;
  io.Write   = SHT40_IO_Write;
  io.Read    = SHT40_IO_Read;
  io.GetTick = SHT40_IO_GetTick;
  io.Delay   = HAL_Delay;

  if (SHT40AD1B_RegisterBusIO(&sht40, &io) != SHT40AD1B_OK)
  {
    return SHT40AD1B_ERROR;
  }
  if (SHT40AD1B_Init(&sht40) != SHT40AD1B_OK)
  {
    return SHT40AD1B_ERROR;
  }
  (void)SHT40AD1B_TEMP_Enable(&sht40);
  (void)SHT40AD1B_HUM_Enable(&sht40);

  /* The driver has no ID register: check that the sensor
     acknowledges its address. */
  if (HAL_I2C_IsDeviceReady(&hi2c2, SHT40AD1B_I2C_ADDRESS, 3, 100) != HAL_OK)
  {
    return SHT40AD1B_ERROR;
  }
  return SHT40AD1B_OK;
}

