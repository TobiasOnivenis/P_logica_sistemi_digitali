/* The SHT40 has no registers: the driver only passes the command byte to write... */
static int32_t SHT40_IO_Write(uint16_t Addr, uint8_t *pData, uint16_t Length)
{
  return (HAL_I2C_Master_Transmit(&hi2c2, Addr, pData, Length, 100) == HAL_OK)
         ? SHT40AD1B_OK : SHT40AD1B_ERROR;
}

/* ...and the 6 bytes to read: T MSB, T LSB, CRC, RH MSB, RH LSB, CRC. */
static int32_t SHT40_IO_Read(uint16_t Addr, uint8_t *pData, uint16_t Length)
{
  return (HAL_I2C_Master_Receive(&hi2c2, Addr, pData, Length, 100) == HAL_OK)
         ? SHT40AD1B_OK : SHT40AD1B_ERROR;
}

static int32_t SHT40_IO_GetTick(void)
{
  return (int32_t)HAL_GetTick();
}


